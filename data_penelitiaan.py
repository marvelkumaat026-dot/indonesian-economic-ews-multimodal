class FuzzyEngineMamdani:
    """
    Modul Algoritma Logika Fuzzy (Mamdani FIS)
    Memproses Fuzzifikasi, Evaluasi Rule Base, dan Defuzzifikasi (Centroid)
    """
    @staticmethod
    def trimf(x, params):
        """Fungsi Keanggotaan Segitiga (Triangular Membership Function)"""
        a, b, c = params
        return np.maximum(0, np.minimum((x - a) / (b - a + 1e-6), (c - x) / (c - b + 1e-6)))

    @staticmethod
    def trapmf(x, params):
        """Fungsi Keanggotaan Trapesium (Trapezoidal Membership Function)"""
        a, b, c, d = params
        return np.maximum(0, np.minimum(np.minimum((x - a) / (b - a + 1e-6), 1.0), (d - x) / (d - c + 1e-6)))

    @classmethod
    def evaluate_fuzzy_risk(cls, isp, volatility_pct):
        """
        Fuzzy EWS: Menghitung Skor Risiko (%) menggunakan aturan Fuzzy Mamdani
        Input 1: Indeks Sosiopolitik (Isp) [0.0 - 1.0]
        Input 2: Volatilitas Kurs (%) [0.0 - 10.0%]
        Output : Fuzzy Risk Score (%) [0.0 - 100.0%]
        """
        # 1. Fuzzifikasi Input 1: Isp (Rendah, Sedang, Tinggi)
        isp_low = cls.trapmf(isp, [0.0, 0.0, 0.25, 0.45])
        isp_med = cls.trimf(isp, [0.35, 0.55, 0.75])
        isp_high = cls.trapmf(isp, [0.65, 0.85, 1.0, 1.0])

        # Fuzzifikasi Input 2: Volatilitas Kurs (Rendah, Sedang, Tinggi)
        vol_low = cls.trapmf(volatility_pct, [0.0, 0.0, 1.5, 3.0])
        vol_med = cls.trimf(volatility_pct, [2.0, 3.5, 5.0])
        vol_high = cls.trapmf(volatility_pct, [4.5, 6.5, 10.0, 10.0])

        # 2. Rule Base (Inferensi Fuzzy Mamdani - Operator Max-Min)
        # Rule 1: IF Isp HIGH OR Volatility HIGH THEN Risk HIGH
        r1_strength = np.maximum(isp_high, vol_high)
        # Rule 2: IF Isp MEDIUM AND Volatility MEDIUM THEN Risk MEDIUM
        r2_strength = np.minimum(isp_med, vol_med)
        # Rule 3: IF Isp LOW AND Volatility LOW THEN Risk LOW
        r3_strength = np.minimum(isp_low, vol_low)
        # Rule 4: IF Isp HIGH AND Volatility LOW THEN Risk MEDIUM
        r4_strength = np.minimum(isp_high, vol_low)

        # Agregasi Kekuatan Implikasi
        risk_high_degree = r1_strength
        risk_med_degree = np.maximum(r2_strength, r4_strength)
        risk_low_degree = r3_strength

        # 3. Defuzzifikasi Centroid (Pusat Area / Weighted Average)
        x_risk = np.linspace(0, 100, 101)
        mu_low = cls.trapmf(x_risk, [0, 0, 20, 40]) * risk_low_degree
        mu_med = cls.trimf(x_risk, [30, 50, 70]) * risk_med_degree
        mu_high = cls.trapmf(x_risk, [60, 80, 100, 100]) * risk_high_degree

        aggregated_output = np.maximum(np.maximum(mu_low, mu_med), mu_high)

        # Menghitung titik berat Centroid
        sum_aggregated = np.sum(aggregated_output)
        if sum_aggregated == 0:
            fuzzy_risk_score = 20.0
        else:
            fuzzy_risk_score = np.sum(x_risk * aggregated_output) / sum_aggregated

        return fuzzy_risk_score

